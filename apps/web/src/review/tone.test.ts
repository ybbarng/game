import { describe, expect, it } from "vitest";

import { commentaryProblems } from "./tone";

describe("해설 줄 말투", () => {
  it("해요체 마침표 문장은 통과한다", () => {
    expect(
      commentaryProblems([
        "둘 수 있는 수가 이것뿐이에요.",
        "고수도 같은 수(e4)를 둬요(승률 55%).",
      ]),
    ).toEqual([]);
  });

  it("꼬리표 줄은 마침표 없이 통과한다", () => {
    expect(
      commentaryProblems([
        "1판 12수째, 민준(흑) 차례 · 따낸 돌 흑 2 · 백 1",
        "다른 후보: ♠K 돈 +20, ♥A 돈 −10",
        "민준: 헛외침",
        "버린 더미 12장을 다시 섞음",
        "나눠 줄 때 묶음마다(원작에는 없음)",
      ]),
    ).toEqual([]);
  });

  it("마침표 없는 해라체·해요체 문장을 잡는다", () => {
    expect(
      commentaryProblems([
        "둘 수 있는 수가 이것뿐이다",
        "공약 단계 · 아직 아무도 출마하지 않았다",
        "쉬었다(둘이 이어 쉬면 판 위 그대로 센다)",
        "민준이 우주국을 지나며 지원금을 받았어요",
      ]),
    ).toEqual([
      "마침표 없는 문장: 둘 수 있는 수가 이것뿐이다",
      "마침표 없는 문장: 공약 단계 · 아직 아무도 출마하지 않았다",
      "마침표 없는 문장: 쉬었다(둘이 이어 쉬면 판 위 그대로 센다)",
      "마침표 없는 문장: 민준이 우주국을 지나며 지원금을 받았어요",
    ]);
  });

  it("마침표가 있어도 해라체면 잡는다", () => {
    expect(commentaryProblems(["상대에 이어 쉬어 판이 끝났다."])).toEqual([
      "해요체 아님: 상대에 이어 쉬어 판이 끝났다.",
    ]);
  });

  it("꼬리표에 섞인 문장 조각을 잡는다", () => {
    expect(
      commentaryProblems([
        "고수라면 Nf3",
        "남의 패를 64가지로 추측해 끝까지 둬 보면 이 수(♠A)는 평균 돈 +30",
      ]),
    ).toEqual([
      "꼬리표 속 문장 조각: 고수라면 Nf3",
      "꼬리표 속 문장 조각: 남의 패를 64가지로 추측해 끝까지 둬 보면 이 수(♠A)는 평균 돈 +30",
    ]);
  });
});
