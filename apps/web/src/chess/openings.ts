import type { LineNode, StudyLine } from "@/study/line";

/** "e4", ["e5", "설명"] 꼴을 마디로 */
type Raw = string | readonly [string, string];
const nodes = (moves: readonly Raw[]): LineNode[] =>
  moves.map((m) =>
    typeof m === "string" ? { move: m } : { move: m[0], note: m[1] },
  );

/** 본줄기 `main`의 `at`번째 마디(0부터)에 갈래를 붙인다 */
function withBranches(
  main: LineNode[],
  at: number,
  ...branches: (readonly Raw[])[]
): LineNode[] {
  const node = main[at];
  if (!node) throw new Error(`갈래 자리 없음: ${at}`);
  main[at] = { ...node, branches: branches.map(nodes) };
  return main;
}

