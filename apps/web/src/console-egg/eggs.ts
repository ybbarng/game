/**
 * 개발자 도구 콘솔을 열면 보이는 인사(2026-11-04 사용자 요청). 홈·게임마다 하나씩 둔다.
 *
 * - 그림(`art`)은 고정폭 글꼴을 가정하고 영문·기호만 쓴다(한글은 폭이 2라 줄이 어긋난다). 휴대폰 원격 디버깅처럼
 *   좁은 콘솔에서도 깨지지 않게 한 줄 60자 안쪽(시험이 확인한다).
 * - 글(`lines`)은 쉬운 한국어, 문장은 마침표로 끝낸다. 사실과 다른 말, 부정을 부추기는 말은 넣지 않는다.
 * - 「멘탈 포커」라는 낱말은 쓰지 않는다: 여러 탭 화면 시험(e2e/fair-multi)이 그 낱말이 든 콘솔 글을 오류로 센다.
 *   그래서 「모두의 기기가 차례로 잠그고 섞는다」처럼 하는 일을 말한다.
 * - 하늘의 별 따기는 docs/41 낱말과 말투(「~습니다」, 관측·예측서)를 따른다.
 * - 링크 값이 `/`로 시작하면 찍을 때 사이트 주소를 앞에 붙인다(콘솔에서 눌러 열 수 있게).
 */
export type EggKey = "home" | GameEntry["id"] | "security" | "learn";

export type Egg = {
  /** 맨 위 띠에 들어갈 이름 */
  title: string;
  /** 띠 바탕색. 글자는 흰색이라 어두운 색만 쓴다(콘솔이 밝든 어둡든 띠 안에서 읽힌다) */
  accent: string;
  /** 고정폭 그림. 한 줄 60자 안쪽, 영문·기호만 */
  art: readonly string[];
  lines: readonly string[];
  /** 표가 어울리는 게임만(숫자야구 판정표) */
  table?: {
    caption: string;
    rows: readonly Record<string, string>[];
  };
  links: readonly { label: string; value: string }[];
};

/** 위아래 빈 줄을 걷어 낸 여러 줄 그림. 태그 템플릿이라 `\`를 그대로 쓴다(String.raw처럼) */
function art(strings: TemplateStringsArray): string[] {
  const rows = strings.raw.join("").split("\n");
  while (rows.length > 0 && rows[0]?.trim() === "") rows.shift();
  while (rows.length > 0 && rows.at(-1)?.trim() === "") rows.pop();
  return rows.map((row) => row.replace(/\s+$/, ""));
}

