/*
 * 오목 수 배우기 문제(docs/23, docs/20 7절). 렌주 규칙(게임 기본값) 15줄 판이고 늘 흑(나)이 둔다. 자리는 "H8"처럼 쓴다.
 * 장면은 컴퓨터끼리 둔 판에서 엔진으로 "정답이 하나뿐인 판"을 찾아 골랐고, study.test.ts가 모든 문제를 다시 확인한다.
 * - attack: 사(넷)로 몰아 `moves`수 안에 다섯을 만든다. 그 수 안에 이기는 첫 수는 정답 하나뿐이고, 더 빨리는 못 이긴다
 * - defend: 백이 사로 몰아 `within`수 안에 이기는 길이 있다. 그 길을 모두 끊는 흑 자리는 `answers`뿐이다
 * - pick: 「이 판에서 좋은 수는?」. `reason`이 좋은 수의 뜻이고, 그 뜻에 맞는 자리는 `answers`뿐이다(study.test.ts)
 *   - opening: 흑 셋째 수로 화월(직접)·포월(간접)을 만드는 자리(docs/20 10절 출처)
 *   - build: 백의 열린 셋을 막으면서(백이 3수 안에 못 이긴다) 흑 열린 셋도 생기는 자리
 * 해설은 장면에서 만든다(study.ts).
 */

export type OmokPuzzle = {
  id: string;
  /** 규칙. 없으면 렌주(게임 기본값) */
  variant?: "renju";
  black: readonly string[];
  white: readonly string[];
  /** 첫 수 목표. 없으면 묶음의 `prompt` */
  goal?: string;
} & (
  | {
      kind: "attack";
      moves: number;
      solution: string;
      /** 백에게 열린 셋이 있는데 먼저 이기는 판(해설 첫머리에 짚는다) */
      race?: true;
    }
  | { kind: "defend"; within: number; answers: readonly string[] }
  | {
      kind: "pick";
      reason: "opening" | "build";
      answers: readonly string[];
    }
);

export interface OmokPuzzleSet {
  id: string;
  title: string;
  summary: string;
  /** 문제 화면 위에 보일 목표 */
  prompt: string;
  /** 틀렸을 때 보일 도움말 */
  hint: string;
  puzzles: readonly OmokPuzzle[];
}

type Scene = { black: string[]; white: string[] };

const attack = (
  prefix: string,
  moves: number,
  scenes: readonly (Scene & { answer: string })[],
): OmokPuzzle[] =>
  scenes.map((s, i) => ({
    id: `${prefix}-${i + 1}`,
    kind: "attack",
    moves,
    black: s.black,
    white: s.white,
    solution: s.answer,
  }));

const defend = (
  prefix: string,
  scenes: readonly (Scene & { answers: string[] })[],
): OmokPuzzle[] =>
  scenes.map((s, i) => ({
    id: `${prefix}-${i + 1}`,
    kind: "defend",
    within: 3,
    black: s.black,
    white: s.white,
    answers: s.answers,
  }));

