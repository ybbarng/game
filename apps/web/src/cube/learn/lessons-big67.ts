const FLIP_5 = EDGES_5X5.find((c) => c.id === "edges-5x5-flip")?.algs[0];
if (FLIP_5 === undefined) throw new Error("공식 없음: edges-5x5-flip");

/** 토끼이빨 공식(5×5 날개 바꾸기와 같은 꼴)의 2R·2L을 다른 층으로 바꾼다 */
const rabbitAt = (layer: string) =>
  FLIP_5.replace(/\b2([RL])/g, (_, f: string) =>
    layer.includes("-") ? `${layer}${f}w` : `${layer}${f}`,
  );

