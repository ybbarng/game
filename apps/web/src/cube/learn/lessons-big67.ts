export const BAR_IN_2 = "2R U2 2R'";
/** 막대 넣기(3R 층 → 3L 층) */
export const BAR_IN_3 = "3R U2 3R'";
/** 넣을 자리가 윗면 3R 층이면 U2로 3L 층에 옮긴 뒤 막대 넣기 */
export const BAR_ALIGN = `U2 ${BAR_IN_3}`;
