const oll = (
  n: number,
  group: string,
  name: string,
  algs: string[],
  note?: string,
): AlgCase => ({
  id: `oll-${n}`,
  set: "oll",
  name: `OLL ${n} ${name}`,
  group,
  algs,
  ...(note === undefined ? {} : { note }),
});

