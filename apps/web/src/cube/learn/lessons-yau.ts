/** 십자 셋 시연(짝 방향이 어긋남): y2로 쥐면 흰-파랑이 앞-왼쪽에 짝지어 있고 흰색이 앞. 2U'·2D로 앞-오른쪽(흰색 오른쪽)에 옮겨 F */
