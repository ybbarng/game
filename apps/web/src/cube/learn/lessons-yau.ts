export const YAU_CROSS3_STATE = "z2 R 2U R' 2D' R2 2U2 R 2D";
/** 십자 셋 단원 시연: 흰-파랑 날개 둘을 2U'로 짝짓고 R로 올려 U'로 뒷면 위에 둔 뒤 B2로 내린다 */
export const YAU_CROSS_PAIR_DEMO = "2U' R U' B2";
/** 십자 셋 단원 해 보기: 흰-빨강 날개 둘을 2D로 짝짓고 R로 올려 U2로 왼쪽 면 위에 둔 뒤 L2로 내린다 */
export const YAU_CROSS_PAIR_TRY = "2D R U2 L2";
/** 옆 센터 단원 시연: 뒷면 윗줄 주황 센터 블럭을 2U로 데려와(위-뒤 칸) R로 아랫줄에 넣고 되돌린다(yau-path.ts) */
export const YAU_SIDE_DEMO = "2U R 2U'";
/** 옆 센터 해 보기: R2로 아래-뒤 칸을 비우고, 뒷면 윗줄에서 데려온 블럭(위-앞 칸)을 R'로 넣는다 */
export const YAU_SIDE_TRY = "R2 2U R' 2U'";
/** 옆 센터 해 보기: 오른쪽 면에 모은 초록을 2U 2D'로 앞면에 보내고, 뒷면 아랫줄 주황 블럭(아래-뒤 칸)을 넣는다 */
