/**
 * 미니 모드의 거울(뒷면 판)은 직접 맞추는 동안만 보인다(docs/47 15-14, 2026-11-09 사용자 「풀 때만 거울 표시하고」).
 *
 * - 보인다: 메뉴 「거울」이 켜져 있고, 창이 거울을 담을 만큼 크고(`MINI_MIRROR_PER_N`), 포커스가 있고, 큐브가 섞인 상태.
 *   섞으면 나타나고(첫 수 전 살펴보는 동안도), 맞추면 사라진다.
 * - 숨는다: 포커스가 없을 때(떠 있을 때의 홈 시연·내 판 다시 보기·조금 섞었다 되돌리기와 그 사이 쉬는 동안 모두),
 *   맞춘 큐브일 때(포커스가 있어도), 떠 있을 때 움직임이 도는 동안.
 *   맞춘 큐브에 포커스만 있을 때 숨기는 까닭: 볼 뒷면이 없고(모든 면이 한 색), 섞기 키를 누르면 바로 나타나서
 *   맞추기 시작을 알리는 신호가 된다. 포커스를 오가며 거울이 깜빡이지도 않는다(맞춘 큐브는 포커스와 상관없이 숨음).
 */
export function miniMirrorShown(o: {
  /** 메뉴 「거울」 */
  wanted: boolean;
  /** 창이 거울을 담을 만큼 큰지(작으면 저절로 접힘) */
  fits: boolean;
  focused: boolean;
  solved: boolean;
  /** 떠 있을 때 움직임이 도는 중인지 */
  idle: boolean;
}): boolean {
  return o.wanted && o.fits && o.focused && !o.solved && !o.idle;
}
